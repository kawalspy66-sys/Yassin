create extension if not exists pgcrypto;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  maker text not null check (char_length(maker) between 1 and 80),
  category text not null check (category in ('Home', 'Flowers', 'Accessories', 'Beauty', 'Food')),
  price numeric(10, 2) not null check (price > 0),
  rating numeric(2, 1) not null default 5 check (rating between 0 and 5),
  reviews integer not null default 0 check (reviews >= 0),
  badge text not null default '' check (char_length(badge) <= 40),
  image text not null default 'photo-1490312278390-ab64016e0aa9' check (char_length(image) <= 500),
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_name text not null check (char_length(customer_name) between 1 and 100),
  customer_phone text not null check (char_length(customer_phone) between 3 and 40),
  customer_address text not null check (char_length(customer_address) between 5 and 500),
  total numeric(10, 2) not null check (total > 0),
  status text not null default 'New' check (status in ('New', 'Processing', 'Shipped', 'Completed', 'Cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint not null,
  name text not null,
  price numeric(10, 2) not null check (price > 0),
  quantity integer not null check (quantity between 1 and 100)
);

create or replace function public.is_marketly_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_marketly_admin() from public;
grant execute on function public.is_marketly_admin() to authenticated;

alter table public.products enable row level security;
alter table public.admin_users enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

