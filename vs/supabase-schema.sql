create or replace function public.place_marketly_order(
  p_customer_name text,
  p_customer_phone text,
  p_customer_address text,
  p_items jsonb
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_order_id uuid;
  calculated_total numeric(10, 2);
  matched_products integer;
begin
  if char_length(trim(coalesce(p_customer_name, ''))) not between 1 and 100
    or char_length(trim(coalesce(p_customer_phone, ''))) not between 3 and 40
    or char_length(trim(coalesce(p_customer_address, ''))) not between 5 and 500 then
    raise exception 'Please provide valid delivery details.';
  end if;

  if coalesce(jsonb_typeof(p_items), '') <> 'array'
    or jsonb_array_length(p_items) not between 1 and 50 then
    raise exception 'The order must contain between 1 and 50 items.';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_items) as item(value)
    where coalesce(item.value->>'id', '') !~ '^[0-9]+$'
      or coalesce(item.value->>'quantity', '') !~ '^[0-9]+$'
      or coalesce(item.value->>'quantity', '0')::integer not between 1 and 100
  ) then
    raise exception 'The order contains an invalid item.';
  end if;

  if exists (
    select 1 from (
      select (item.value->>'id')::bigint as product_id
      from jsonb_array_elements(p_items) as item(value)
      group by (item.value->>'id')::bigint
      having count(*) > 1
    ) duplicates
  ) then
    raise exception 'The order contains duplicate items.';
  end if;

  select count(*), coalesce(sum(product.price * (item.value->>'quantity')::integer), 0)
    into matched_products, calculated_total
  from jsonb_array_elements(p_items) as item(value)
  join public.products as product on product.id = (item.value->>'id')::bigint;

  if matched_products <> jsonb_array_length(p_items) then
    raise exception 'One or more products are no longer available.';
  end if;

  insert into public.orders (
    customer_name, customer_phone, customer_address, total
  ) values (
    trim(p_customer_name), trim(p_customer_phone), trim(p_customer_address), calculated_total
  ) returning id into new_order_id;

  insert into public.order_items (order_id, product_id, name, price, quantity)
  select new_order_id, product.id, product.name, product.price, (item.value->>'quantity')::integer
  from jsonb_array_elements(p_items) as item(value)
  join public.products as product on product.id = (item.value->>'id')::bigint;

  return new_order_id;
end;
$$;

